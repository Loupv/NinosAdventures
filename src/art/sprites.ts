/** Le portail : des anneaux concentriques qui défilent vers l'intérieur. */
function portalRings(phase: number): Art {
  const rows: string[] = [];
  for (let y = 0; y < 16; y++) {
    let row = '';
    for (let x = 0; x < 16; x++) {
      const d = Math.hypot(x - 7.5, y - 7.5);
      if (d > 7.6) {
        row += '.';
        continue;
      }
      const band = (((Math.floor(d - phase) % 3) + 3) % 3) as 0 | 1 | 2;
      row += band === 0 ? '0' : band === 1 ? '1' : '3';
    }
    rows.push(row);
  }
  return rows;
}


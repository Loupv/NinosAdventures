/**
 * Un meuble rectangulaire, décrit comme une pile de bandes horizontales
 * [hauteur, ton]. Taper 40 caractères par ligne à la main est une source de
 * bugs ; décrire les bandes ne l'est pas.
 */
function stack(w: number, bands: Array<[number, string]>, legs = 0): string[] {
  const rows: string[] = [];
  for (const [n, tone] of bands) {
    const row = tone === '0' ? '0'.repeat(w) : '0' + tone.repeat(w - 2) + '0';
    for (let i = 0; i < n; i++) rows.push(row);
  }
  for (let i = 0; i < legs; i++) rows.push('00' + '.'.repeat(w - 4) + '00');
  return rows;
}

/** Remplace un caractère : sert à poser une poignée, une serrure, un bouton. */
function poke(art: string[], x: number, y: number, ch: string): void {
  art[y] = art[y].slice(0, x) + ch + art[y].slice(x + 1);
}

/** Table ronde : plateau elliptique clair, pied central. */
function roundTable(w: number, h: number): Art {
  const topH = h - 6;
  const rows: string[] = [];
  for (let y = 0; y < h; y++) {
    let row = '';
    for (let x = 0; x < w; x++) {
      if (y < topH) {
        const dx = (x - (w - 1) / 2) / ((w - 1) / 2);
        const dy = (y - (topH - 1) / 2) / ((topH - 1) / 2);
        const d = dx * dx + dy * dy;
        row += d > 1 ? '.' : d > 0.7 ? '0' : y < topH / 2 ? '3' : '2';
      } else {
        row += Math.abs(x - (w - 1) / 2) <= 2.5 ? '0' : '.';
      }
    }
    rows.push(row);
  }
  return rows;
}

/**
 * Canapé vu de dessus, tourné vers la droite : dossier à gauche, accoudoirs en
 * haut et en bas, assise en ton moyen pour que Moon s'y détache.
 */
function sofaVertical(w: number, h: number): Art {
  const back = 6;
  const arm = 4;
  const rows: string[] = [];
  for (let y = 0; y < h; y++) {
    let row = '';
    for (let x = 0; x < w; x++) {
      if (x === 0 || x === w - 1 || y === 0 || y === h - 1) row += '0';
      else if (x < back) row += x === back - 1 ? '0' : '1';
      else if (y < arm || y >= h - arm) row += y === arm || y === h - arm - 1 ? '0' : '1';
      else row += (y - arm) % 4 === 0 ? '3' : '2';
    }
    rows.push(row);
  }
  return rows;
}

/** Bibliothèque : des rayonnages remplis de tranches de livres. */
function bookshelf(w: number, shelves: number, shelfH: number): Art {
  const tones = '3213123212';
  const rows: string[] = ['0'.repeat(w)];
  for (let s = 0; s < shelves; s++) {
    for (let i = 0; i < shelfH; i++) {
      let row = '0';
      for (let x = 1; x < w - 1; x++) row += tones[(x + s * 3) % tones.length];
      rows.push(row + '0');
    }
    rows.push('0'.repeat(w));
  }
  return rows;
}


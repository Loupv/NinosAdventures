function bookshelf(w: number, shelves: number, shelfH: number): Art {
  const tones = '3213123212';
  const rows: string[] = ['0'.repeat(w)];
  for (let s = 0; s < shelves; s++) {
    for (let i = 0; i < shelfH; i++) {
      let row = '0';
      for (let x = 1; x < w - 1; x++) row += tones[(x + s * 3) % tones.length];
      rows.push(row + '0');
    }
    rows.push('0'.repeat(w));
  }
  return rows;
}

